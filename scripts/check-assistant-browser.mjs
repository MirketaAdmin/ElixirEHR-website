import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright');
const base = process.env.ASSISTANT_TEST_URL ?? 'http://127.0.0.1:5173';
const screenshotDir = process.env.ASSISTANT_SCREENSHOT_DIR ?? 'work/assistant-check';
await mkdir(screenshotDir, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; const forbidden = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (/webto\.salesforce|\/api\/chat|calendly|bookings/i.test(request.url())) forbidden.push(request.url()); });
  await page.route('**/*', (route) => route.request().url().startsWith(base) ? route.continue() : route.abort());
  await page.goto(`${base}/behavioral-health-ehr/?tracking=not-for-crm`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Reject Non-Essential', exact: true }).click();
  await page.getByRole('button', { name: 'Ask Elixir', exact: true }).click({ timeout: 10000 });
  const dialog = page.getByRole('dialog', { name: 'Elixir assistant', exact: true });
  await dialog.waitFor();
  await dialog.getByRole('textbox', { name: 'Your question', exact: true }).fill('What can Elixir help with?');
  await dialog.getByRole('button', { name: 'Send message', exact: true }).click();
  await dialog.getByText(/This is a sample reply/).waitFor();
  const question = dialog.getByLabel('What kind of healthcare organization are you with?', { exact: true });
  await question.fill('Behavioral health');
  await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
  await dialog.getByLabel('Which EHR or practice-management system do you use today?', { exact: true }).waitFor();
  await page.screenshot({ path: `${screenshotDir}/conversation-desktop.png` });
  await dialog.getByRole('button', { name: 'Close assistant', exact: true }).click();
  await page.evaluate(() => { window.history.pushState({}, '', '/why-elixir/'); window.dispatchEvent(new PopStateEvent('popstate')); });
  await page.getByRole('button', { name: 'Ask Elixir', exact: true }).click();
  await dialog.getByRole('button', { name: 'Request a demo', exact: true }).click();
  await dialog.getByLabel('First name', { exact: true }).fill('Alex');
  await dialog.getByLabel('Last name', { exact: true }).fill('Sample');
  await dialog.getByLabel('Work email', { exact: true }).fill('sample@example.com');
  await dialog.getByLabel('Organization', { exact: true }).fill('Example Clinic');
  const summary = dialog.getByLabel('Request summary', { exact: true });
  assert.match(await summary.inputValue(), /Behavioral health/);
  assert.match(await summary.inputValue(), /\/behavioral-health-ehr\//);
  assert.doesNotMatch(await summary.inputValue(), /tracking/);
  await summary.fill(`${await summary.inputValue()}\nVisitor correction: evaluating for two locations.`);
  await dialog.getByRole('button', { name: 'Preview demo request', exact: true }).click();
  await dialog.getByText('Preview only. No request has been sent or meeting booked.', { exact: true }).waitFor();
  await page.screenshot({ path: `${screenshotDir}/desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${screenshotDir}/mobile.png` });
  assert.equal(await dialog.evaluate((node) => node.getBoundingClientRect().width <= window.innerWidth), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Ask Elixir', exact: true }).evaluate((node) => node === document.activeElement), true);
  assert.deepEqual(forbidden, []);
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile chat, qualification, corrections, navigation, review, focus, and zero external submissions.');
} finally { await browser.close(); }
